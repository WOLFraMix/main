package main

import (
	"fmt"
	"strings"
)

/*
Дана текстовая строка. С ней можно выполнять следующие операции:

Заменить один символ строки на другой символ.
Удалить один произвольный символ.
Вставить произвольный символ в произвольное место строки.

Минимальное количество таких операций,
при помощи которых можно из одной строки получить другую,
называется стоимостью редактирования или расстоянием Левенштейна.

Определите расстояние Левенштейна для двух данных строк.
*/

func levenshteinDistance(s1, s2 string) int {
	// Получаем длины строк
	len1, len2 := len(s1), len(s2)

	// Создаем матрицу для динамического программирования
	// dp[i][j] будет хранить минимальное количество операций для преобразования
	dp := make([][]int, len1+1)
	for i := range dp {
		dp[i] = make([]int, len2+1)
	}

	// Инициализация первой строки и первого столбца
	// Если одна из строк пустая,
	// то расстояние равно длине другой строки
	for i := 0; i <= len1; i++ {
		dp[i][0] = i
	}
	for j := 0; j <= len2; j++ {
		dp[0][j] = j
	}

	// Заполнение таблицы
	for i := 1; i <= len1; i++ {
		for j := 1; j <= len2; j++ {
			// Если символы совпадают,
			// стоимость замены 0, иначе 1
			cost := 0
			if s1[i-1] != s2[j-1] {
				cost = 1
			}

			// Выбираем минимальную стоимость из трех возможных операций:
			// 1. Удаление символа из первой строки (dp[i-1][j] + 1)
			// 2. Вставка символа во вторую строку (dp[i][j-1] + 1)
			// 3. Замена символа (dp[i-1][j-1] + cost)
			dp[i][j] = min(dp[i-1][j]+1, dp[i][j-1]+1, dp[i-1][j-1]+cost)
		}
	}

	// Результат — в правом нижнем углу матрицы
	return dp[len1][len2]
}

// Вспомогательная функция для поиска минимума
func min(nums ...int) int {
	minVal := nums[0]
	for _, n := range nums {
		if n < minVal {
			minVal = n
		}
	}
	return minVal
}

func main() {
	// Считываем две строки
	var s1, s2 string
	fmt.Scan(&s1, &s2)

	// Приводим строки к верхнему регистру
	fmt.Println(levenshteinDistance(strings.ToUpper(s1), strings.ToUpper(s2)))
}
