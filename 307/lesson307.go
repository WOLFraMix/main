package main

import (
	"fmt"
)

/*
Рассмотрим фигуру - большой равносторонний треугольник,
составленный из маленьких равносторонних треугольников.
Напишите программу, которая будет определять,
сколько всего в ней треугольников
(необходимо учитывать не только «маленькие» треугольники,
а вообще все треугольники).
*/

func main() {
	var n int
	fmt.Scan(&n)

	var count int64

	// Часть 1: Подсчет треугольных чисел
	// Формула i*(i+1)/2 вычисляет:
	// сумму чисел от 1 до i (i-е треугольное число).
	// Цикл суммирует эти значения для всех i от 1 до n.
	for i := 1; i <= n; i++ {
		count += int64(i) * int64(i+1) / 2
	}

	// Часть 2: Подсчет дополнительных комбинаций
	// Цикл проходит по всем возможным длинам k (от n-1 до 1).
	// Для каждой длины k вычисляется количество способов выбрать
	// два непересекающихся отрезка на отрезке длины n.
	for i := 1; i <= n-1; i++ {
		k := n - i // текущая длина рассматриваемого отрезка
		if k%2 == 0 {
			// Если длина k четная,
			// используется формула (k * (k + 2)) / 4
			count += int64(k) * int64(k+2) / 4
		} else {
			// Если длина k нечетная,
			// используется формула ((k + 1) * (k + 1)) / 4
			count += int64(k+1) * int64(k+1) / 4
		}
	}

	// Выводим итоговую сумму
	fmt.Println(count)
}
