package main

import (
	"fmt"
)

// copyTime вычисляет минимальное время для создания n копий на двух устройствах.
// n - количество необходимых копий
// x - время создания одной копии на первом устройстве
// y - время создания одной копии на втором устройстве
func copyTime(n, x, y int) int {
	if n <= 0 {
		return 0
	}

	// Вспомогательная функция для нахождения максимума
	max := func(a, b int) int {
		if a > b {
			return a
		}
		return b
	}

	// Вспомогательная функция для нахождения минимума
	min := func(a, b int) int {
		if a < b {
			return a
		}
		return b
	}

	left := 0
	// Правая граница: худший случай, когда все копии делает более медленное устройство
	right := (n - 1) * max(x, y)

	// Бинарный поиск
	for left+1 < right {
		middle := (right + left) / 2

		// Проверка условия: сколько копий можно сделать за время middle
		// middle/x + middle/y < n-1 означает, что за это время мы не успеваем сделать нужное количество
		if middle/x+middle/y < n-1 {
			left = middle
		} else {
			right = middle
		}
	}

	// Возвращаем результат с учетом времени первой копии (минимум из x и y)
	return right + min(x, y)
}

func main() {
	// Пример 1: Нужно 4 копии, устройства работают за 1 и 1 секунду
	n1, x1, y1 := 4, 1, 1
	result1 := copyTime(n1, x1, y1)
	fmt.Printf("Пример 1: n=%d, x=%d, y=%d -> Время: %d сек\n", n1, x1, y1, result1)
	// Ожидаемый результат: 3 (1 сек на первую копию + 2 сек на остальные 3 копии параллельно)

	// Пример 2: Нужно 5 копий, устройства работают за 1 и 2 секунды
	n2, x2, y2 := 5, 1, 2
	result2 := copyTime(n2, x2, y2)
	fmt.Printf("Пример 2: n=%d, x=%d, y=%d -> Время: %d сек\n", n2, x2, y2, result2)
	// Ожидаемый результат: 4

	// Пример 3: Нужно 1 копия (тривиальный случай)
	n3, x3, y3 := 1, 5, 10
	result3 := copyTime(n3, x3, y3)
	fmt.Printf("Пример 3: n=%d, x=%d, y=%d -> Время: %d сек\n", n3, x3, y3, result3)
	// Ожидаемый результат: 5
}
